import {
  Registry,
  allNodeDefs,
  allAttachmentDefs,
  allEnums,
  attachmentsForNode,
  isArrayType,
  isEnumType,
  TRANSFORM_ATTRS,
  type EnumDef,
  type PropertyMeta,
  type NodeAttr,
  type NodeDef,
  type AttachmentDef,
} from '@scenoco-three/core/internal';
import { codecs, type ScalarType } from '../dsl/types.js';

/**
 * Generates a no-namespace XSD 1.0 from the live registries (node tags +
 * components). Point an editor's XML language server at it (via
 * `xsi:noNamespaceSchemaLocation="scene.xsd"`) to get attribute autocomplete and
 * inline validation for free — the same data the runtime Validator checks, in a
 * form stock IDE tooling understands.
 *
 * The structure favors editor assistance over strict validation (e.g. it does
 * not enforce "exactly one geometry per Mesh" — that's the Validator's job and
 * would fight XSD 1.0's Unique Particle Attribution rule). Every element still
 * carries a precise, typed attribute list.
 */
export function generateXsd(): string {
  const defs = allNodeDefs();
  const byKind = (k: NodeDef['kind']) => defs.filter((d) => d.kind === k);

  const out: string[] = [];
  out.push(`<?xml version="1.0" encoding="UTF-8"?>`);
  out.push(`<!-- Generated by scenoco. Do not edit by hand; run \`scenoco export\`. -->`);
  out.push(`<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" elementFormDefault="qualified">`);
  out.push('');

  // --- Reusable simple types for math/reference attribute values -----------
  out.push(`  <!-- Value formats -->`);
  for (const t of ['vec2', 'vec3', 'euler', 'color'] as const) {
    out.push(simpleType(t, codecs[t].xsd.pattern!));
  }
  out.push(simpleType('ref', '#\\S+')); // a "#id" reference
  // Registered enums → a named simpleType each, referenced by enum-typed attributes.
  for (const e of allEnums()) out.push(enumSimpleType(e));
  out.push('');

  // --- Shared transform attributes (every spatial node) --------------------
  out.push(`  <!-- Transform attributes shared by all spatial nodes -->`);
  out.push(`  <xs:attributeGroup name="transform">`);
  out.push(`    <xs:attribute name="id" type="xs:string"/>`);
  for (const [name, meta] of Object.entries(TRANSFORM_ATTRS)) {
    out.push(nodeAttr('    ', name, meta));
  }
  out.push(`  </xs:attributeGroup>`);
  out.push('');

  // --- Attachment elements (geometry/material/fog/…) -----------------------
  out.push(`  <!-- Attachments: leaves that configure a node (per-node allowed set below) -->`);
  for (const def of allAttachmentDefs()) out.push(attachmentElement(def));
  out.push('');

  // --- Components -----------------------------------------------------------
  out.push(`  <!-- Components (children of <Components>) -->`);
  for (const name of Registry.componentNames()) out.push(componentElement(name));
  out.push('');
  out.push(`  <xs:element name="Components">`);
  out.push(`    <xs:complexType>`);
  out.push(`      <xs:choice minOccurs="0" maxOccurs="unbounded">`);
  for (const name of Registry.componentNames()) out.push(`        <xs:element ref="${name}"/>`);
  out.push(`      </xs:choice>`);
  out.push(`    </xs:complexType>`);
  out.push(`  </xs:element>`);
  out.push('');

  // --- Prefab instance + Override (DSL elements, not registered node tags) --
  out.push(`  <!-- Prefab instance: expands a .prefab.xml file in place -->`);
  out.push(prefabElement());
  out.push(overrideElement());
  out.push('');

  // --- Spatial nodes (Object3D family) -------------------------------------
  const object3d = defs.filter((d) => d.kind === 'object3d');
  out.push(choiceGroup('object3dNodes', [...object3d.map((d) => d.tag), 'PrefabInstance']));
  out.push('');
  out.push(`  <!-- Spatial nodes -->`);
  for (const def of [...byKind('scene'), ...object3d]) out.push(spatialElement(def));

  out.push(`</xs:schema>`);
  out.push('');
  return out.join('\n');
}

function prefabElement(): string {
  return [
    `  <xs:element name="PrefabInstance"> <!-- &lt;PrefabInstance src="x.prefab.xml" id="t1" …/&gt; -->`,
    `    <xs:complexType>`,
    `      <xs:choice minOccurs="0" maxOccurs="unbounded">`,
    `        <xs:element ref="Override"/>`,
    `        <xs:element ref="Components"/>`,
    `      </xs:choice>`,
    `      <xs:attribute name="src" type="xs:string" use="required"/> <!-- the .prefab.xml file -->`,
    `      <xs:attributeGroup ref="transform"/> <!-- incl. id (required by the validator) -->`,
    `    </xs:complexType>`,
    `  </xs:element>`,
  ].join('\n');
}

function overrideElement(): string {
  return [
    `  <xs:element name="Override"> <!-- patch a prefab-internal node/component by id -->`,
    `    <xs:complexType>`,
    `      <xs:attribute name="target" type="ref" use="required"/> <!-- #&lt;prefab-local id&gt; -->`,
    `      <xs:anyAttribute processContents="skip"/>`,
    `    </xs:complexType>`,
    `  </xs:element>`,
  ].join('\n');
}

// ---- element builders -----------------------------------------------------

function spatialElement(def: NodeDef): string {
  const lines: string[] = [];
  lines.push(`  <xs:element name="${def.tag}">`);
  lines.push(...xsDoc('    ', def.description));
  lines.push(`    <xs:complexType>`);

  const childRefs: string[] = [];
  // Attachments this node accepts (geometry/material/fog/…).
  for (const att of attachmentsForNode(def)) childRefs.push(`<xs:element ref="${att.tag}"/>`);
  if (def.children.object3d) childRefs.push(`<xs:group ref="object3dNodes"/>`);
  if (def.children.components) childRefs.push(`<xs:element ref="Components"/>`);

  if (childRefs.length > 0) {
    lines.push(`      <xs:choice minOccurs="0" maxOccurs="unbounded">`);
    for (const ref of childRefs) lines.push(`        ${ref}`);
    lines.push(`      </xs:choice>`);
  }

  lines.push(`      <xs:attributeGroup ref="transform"/>`);
  for (const [name, meta] of Object.entries(def.attrs)) lines.push(nodeAttr('      ', name, meta));
  lines.push(`    </xs:complexType>`);
  lines.push(`  </xs:element>`);
  return lines.join('\n');
}

function attachmentElement(def: AttachmentDef): string {
  const attrs = Object.entries(def.attrs).map(([name, meta]) => nodeAttr('      ', name, meta));
  // Any attachment may pull defaults from a resource file via src= (e.g. .material.xml) —
  // unless it already declares its own `src` (e.g. <Model src>), which would otherwise
  // produce a duplicate attribute use and an invalid schema.
  if (!('src' in def.attrs)) {
    attrs.unshift(attrXml('      ', 'src', 'xs:string', false, 'Load attribute defaults from a resource file'));
  }
  return [
    `  <xs:element name="${def.tag}">`,
    ...xsDoc('    ', def.description),
    `    <xs:complexType>`,
    ...attrs,
    `    </xs:complexType>`,
    `  </xs:element>`,
  ].join('\n');
}

function componentElement(name: string): string {
  const meta = Registry.getComponent(name)!.meta;
  const attrs = [`      <xs:attribute name="id" type="xs:string"/>`];
  for (const [attr, prop] of meta.properties) attrs.push(propertyAttr('      ', attr, prop));
  return [
    `  <xs:element name="${name}">`,
    ...xsDoc('    ', meta.description),
    `    <xs:complexType>`,
    ...attrs,
    `    </xs:complexType>`,
    `  </xs:element>`,
  ].join('\n');
}

// ---- attribute / type helpers ---------------------------------------------

function nodeAttr(indent: string, name: string, meta: NodeAttr): string {
  // Array attrs are bracketed lists ("[a,b,c]") — typed loosely as strings.
  const type = isArrayType(meta.type) ? 'xs:string' : xsdType(meta.type);
  return attrXml(indent, name, type, !!meta.required, meta.description);
}

function propertyAttr(indent: string, name: string, meta: PropertyMeta): string {
  return attrXml(indent, name, propertyXsdType(meta.type), !!meta.required, meta.description);
}

/**
 * One `<xs:attribute>`. When a description is present it carries an
 * `xs:annotation/xs:documentation` child (surfaced as IDE hover help by XML
 * language servers); otherwise it stays a terse self-closing element.
 */
function attrXml(indent: string, name: string, type: string, required: boolean, description?: string): string {
  const use = required ? ` use="required"` : '';
  if (!description) return `${indent}<xs:attribute name="${name}" type="${type}"${use}/>`;
  return [
    `${indent}<xs:attribute name="${name}" type="${type}"${use}>`,
    ...xsDoc(`${indent}  `, description),
    `${indent}</xs:attribute>`,
  ].join('\n');
}

/** XSD attribute type for a component property. */
function propertyXsdType(type: PropertyMeta['type']): string {
  // Array props ("[…]") and prefab file paths are typed loosely as strings.
  if (isArrayType(type)) return 'xs:string';
  if (isEnumType(type)) return type.name;
  if (type === 'prefab') return 'xs:string';
  if (typeof type === 'string' && type !== 'node') return xsdType(type);
  return 'ref';
}

/** Map a scalar/enum type to its XSD type name (named simpleType or xs: builtin). */
function xsdType(type: ScalarType | EnumDef): string {
  if (isEnumType(type)) return type.name;
  switch (type) {
    case 'vec2':
    case 'vec3':
    case 'euler':
    case 'color':
      return type;
    default:
      return codecs[type].xsd.base;
  }
}

/** A named simpleType restricting an attribute to an enum's member names. */
function enumSimpleType(def: EnumDef): string {
  const lines = [`  <xs:simpleType name="${def.name}">`, `    <xs:restriction base="xs:string">`];
  for (const member of def.names) lines.push(`      <xs:enumeration value="${escapeXml(member)}"/>`);
  lines.push(`    </xs:restriction>`, `  </xs:simpleType>`);
  return lines.join('\n');
}

function simpleType(name: string, pattern: string): string {
  return [
    `  <xs:simpleType name="${name}">`,
    `    <xs:restriction base="xs:string">`,
    `      <xs:pattern value="${escapeXml(pattern)}"/>`,
    `    </xs:restriction>`,
    `  </xs:simpleType>`,
  ].join('\n');
}

function choiceGroup(name: string, tags: string[]): string {
  const refs = tags.map((t) => `      <xs:element ref="${t}"/>`);
  return [`  <xs:group name="${name}">`, `    <xs:choice>`, ...refs, `    </xs:choice>`, `  </xs:group>`].join('\n');
}

/** Lines for an `xs:annotation/xs:documentation` block (IDE hover help), or none. */
function xsDoc(indent: string, text?: string): string[] {
  if (!text) return [];
  return [
    `${indent}<xs:annotation>`,
    `${indent}  <xs:documentation>${escapeXml(text)}</xs:documentation>`,
    `${indent}</xs:annotation>`,
  ];
}

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
